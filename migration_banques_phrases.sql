CREATE TABLE IF NOT EXISTS public.banques_phrases (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  ortho_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  nom text NOT NULL CHECK (length(trim(nom)) > 0),
  phrases jsonb NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(phrases) = 'array'),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.banques_phrases_patients (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  banque_id uuid NOT NULL REFERENCES public.banques_phrases(id) ON DELETE CASCADE,
  patient_id uuid NOT NULL REFERENCES public.patients(id) ON DELETE CASCADE,
  phrases_par_session integer NOT NULL DEFAULT 5 CHECK (phrases_par_session BETWEEN 1 AND 10),
  epinglees jsonb NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(epinglees) = 'array'),
  UNIQUE (banque_id, patient_id)
);

CREATE TABLE IF NOT EXISTS public.banques_phrases_log (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  patient_id uuid NOT NULL REFERENCES public.patients(id) ON DELETE CASCADE,
  banque_id uuid NOT NULL REFERENCES public.banques_phrases(id) ON DELETE CASCADE,
  phrase_index integer NOT NULL CHECK (phrase_index >= 0),
  essais integer NOT NULL CHECK (essais >= 1),
  date_session date NOT NULL DEFAULT CURRENT_DATE,
  cycle_num integer NOT NULL CHECK (cycle_num >= 1)
);

CREATE INDEX IF NOT EXISTS banques_phrases_ortho_id_idx
  ON public.banques_phrases(ortho_id);
CREATE INDEX IF NOT EXISTS banques_phrases_patients_patient_id_idx
  ON public.banques_phrases_patients(patient_id);
CREATE INDEX IF NOT EXISTS banques_phrases_log_patient_banque_idx
  ON public.banques_phrases_log(patient_id, banque_id, id);
